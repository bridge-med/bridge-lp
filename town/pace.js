/* ================================================================
   舞台の「表示の進み」(live.js の立体と、hiraku.js の止めた画像の両方が使う)
   スクロールの進み(目標。スクロールの位置だけで決まる)を、決まった速さより速くは追わない。スクロールは止めない・吸着しない・横取りしない。
   速くはじいても、絵(カメラ・壁・灯り)と、それに結びついた札・言葉・階の印・出口は、寄る → 壁が倒れる → 3F・2F・1F → 引き上げを短い時間で見せてから追いつく。
   上限より遅いスクロールでは、目標をそのまま渡す(これまでと同じ追従。画素の差なし)。戻る向きも同じ。
   進み q の単位は v6 のまま(1 = v6 の 1.5 画面。舞台の終わり QMAX = 1.482 = 約 2.22 画面)
   ================================================================ */

/* ばね(半陰的オイラーを細かく刻む)。z = 1 で臨界減衰、z < 1 で弾む */
export class Spring {
  constructor(x, w, z = 1) { this.x = x; this.v = 0; this.t = x; this.w = w; this.z = z; }
  step(dt) { const n = Math.max(1, Math.ceil(dt / .004)), h = dt / n, k = this.w * this.w, c = 2 * this.z * this.w; for (let i = 0; i < n; i++) { const a = -k * (this.x - this.t) - c * this.v; this.v += a * h; this.x += this.v * h; } }
  get moving() { return Math.abs(this.x - this.t) > 1e-4 || Math.abs(this.v) > 1e-3; }
  set(x) { this.x = this.t = x; this.v = 0; }
}

/* 区間ごとの、1 画面を通るのに掛ける最短の秒(その区間の始まりの q から)。見どころはやや遅く、何も起きない区間は速く。
   最速で通したとき(393×724 の実測は返事と design-system §1 Motion の v7 の実測): 1F まで 約1.9 秒・舞台ぜんたい 約3.1 秒(平均 1 画面 約1.4 秒。+ばねの遅れ 約0.3 秒) */
const PACE = [
  [0, 1.0],      // 寄り始め: 最初の画面の言葉が消え、町が空気へ溶け、病院へ寄る(.036–.43 の前半)
  [.25, 1.8],    // 前の壁が倒れる .25–.37・沈む .36–.42・外枠と階の印 .38–.43(病院に着く瞬間まで)
  [.43, 1.2],    // 着いた病院ぜんたい・「病院の中」と一文 .45–.49
  [.55, 1.8],    // 3F .565 / 2F .70 / 1F .835 と下の入口(各階 0.2 画面 = 最速でも 約0.36 秒ずつ)。病院を出る戻し(+.15)まで
  [.935, 1.5],   // 閉じ: 病院を出て、引いて上がる(+.15–.55。カメラが動く)
  [1.202, 1.0]   // 閉じ: カメラは見晴らしで止まり、言葉・札・道の先が順に出る(+.55–.97)
];
const QPS = 1.5;   // 1 画面 = 進み 1/1.5
/* 位置 q での上限の速さ(進み/秒) */
export function vcap(q) { let s = PACE[0][1]; for (const [a, v] of PACE) if (q >= a) s = v; return 1 / (s * QPS); }
/* 表示の目標 c を、目標 to へ、dt 秒で上限の速さだけ進める(届けば to そのもの)。区間の境目を越えるときは、刻んで越える */
export function capStep(c, to, dt) {
  for (let n = 0; n < 8 && c !== to && dt > 0; n++) {
    const v = vcap(to > c ? c : c - 1e-9), d = to - c, m = v * dt;
    if (Math.abs(d) <= m) return to;
    const c2 = c + Math.sign(d) * m;
    // 区間の境目で、残りの時間を次の区間の速さで使う
    const edge = to > c ? PACE.find(([a]) => a > c && a < c2) : [...PACE].reverse().find(([a]) => a < c && a > c2);
    if (!edge) return c2;
    dt -= Math.abs(edge[0] - c) / v; c = edge[0];
  }
  return c;
}
