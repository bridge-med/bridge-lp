  function patientLine(persona, ctx, opts) {
    const ch = chOf(persona);
    const o = opts || {};
    const pool = ch[ctx] || ch.wait;
    const idx = Math.abs((o.variant || 0) + (persona ? persona.age : 0)) % pool.length;
    return pool[idx].replace('{wait}', String(Math.round(o.wait || 0)));
  }

