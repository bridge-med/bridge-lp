  function genPatient(id, seg) {
    const r = rng((id + 1) * 7919);
    const prof = PROFILE[seg] || PROFILE.senior;
    const ch = pick(r, CHARACTERS);
    return {
      name: pick(r, SURNAMES),
      age: prof.age[0] + Math.floor(r() * (prof.age[1] - prof.age[0])),
      job: pick(r, prof.jobs),
      complaint: pick(r, prof.complaints),
      chId: ch.id,
      chLabel: ch.label
    };
  }

  function chOf(persona) {
    return CHARACTERS.find((c) => c.id === (persona && persona.chId)) || CHARACTERS[1];
  }

  // 状況に応じたセリフ。variantを変えると同じ人でも言い回しが変わる
  function patientLine(persona, ctx, opts) {
    const ch = chOf(persona);
    const o = opts || {};
    let pool = ch[ctx];
    if (!pool || !pool.length) pool = ch.wait;
    const idx = Math.abs((o.variant || 0) + (persona ? persona.age : 0)) % pool.length;
    return pool[idx].replace('{wait}', String(Math.round(o.wait || 0)));
  }

