/**
 * 調整用の定数はすべてここに置く。
 * 実際の録画で結果がおかしいときは、まずここを変える。
 */

export const UPLOAD = {
  maxBytes: 1024 * 1024 * 1024, // 1GB
  acceptedExtensions: [".mp4", ".mov", ".m4v"],
} as const;

export const FRAME_SELECTION = {
  /** 解析用に動画からサンプルする頻度(枚/秒) */
  sampleFps: 2,
  /** 比較用サムネイルの幅(px)。高さは縦横比から決まる */
  thumbWidth: 90,
  /** 前のサンプルとの差(0〜1)がこれ以下なら「止まっている」 */
  stillDiff: 0.004,
  /**
   * ずらして重ねたときの差がこれ以下なら「スクロール」とみなす(超えると画面遷移)。
   * 合成録画の実測: スクロール 0.002〜0.010 / 問題の切り替え 0.020〜0.040
   */
  scrollMatchDiff: 0.015,
  /** ずらしたときの差が、ずらす前の差のこの割合以下に下がること(偶然の一致を除く) */
  scrollGainRatio: 0.6,
  /** 前に残したフレームから、画面の高さのこの割合だけスクロールしたら次を残す */
  keepScrollRatio: 0.55,
  /** スクロールが止まったとき、これ以上動いていれば止まった画面を残す */
  settleScrollRatio: 0.08,
  /**
   * 直前に残したフレームとの差がこれ以下なら重複として捨てる。
   * 小さい比較画像では「別の問題」でも差が小さく出るため、ほぼ同一の画像だけを捨てる。
   * 見直し等で同じ問題が再び映った分は、文字の段階(mergeOCRText / questionParser)で除く
   */
  duplicateDiff: 0.002,
  /**
   * 全フレームで行の差がこれ以下なら、その行は固定ヘッダー/フッターの一部。
   * 時計の数字が変わる程度(行のごく一部)の差は固定とみなす
   */
  fixedRowDiff: 0.04,
  /** 固定帯とみなす上限(画面の高さに対する割合)。これを超えたら判定できなかったものとする */
  maxFixedBand: 0.25,
} as const;

export const OCR = {
  /** Tesseract の言語。jpn だけで数字・英字もおおむね読める */
  lang: "jpn",
  /** 同時に動かす OCR ワーカー数 */
  workers: 2,
  /** 言語データのキャッシュ先(プロジェクト直下からの相対) */
  cacheDir: ".cache/tessdata",
  /** プレビュー画像の最大幅(px) */
  previewWidth: 720,
} as const;

export const MERGE = {
  /** 2行を「同じ行」とみなす類似度(0〜1) */
  lineSimilarity: 0.75,
  /** 画面の上下この割合の帯にある行は、固定ヘッダー/フッターの候補 */
  chromeBand: 0.12,
  /** 帯の中の行が全フレームのこの割合以上に出ていれば固定バーとして除く */
  chromeMinRatio: 0.5,
  /** 新しいフレームの行がこの割合以上すでに出ていれば重複として捨てる */
  containedRatio: 0.8,
  /** 重複を探す範囲(直近の行数) */
  lookbackLines: 120,
  /** OCR の信頼度(0〜100)がこれ未満の行は、隠れかけた文字などのノイズとして捨てる */
  minLineConfidence: 10,
  /** フレームのつなぎ目で、端の読み崩れた行を何行まで読み飛ばすか */
  edgeSkipLines: 2,
} as const;
