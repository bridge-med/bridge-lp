/* =========================================================================
 * ふたつめの波 — stages.js
 * 面の定義だけを置く。ここを足せば面が増える。
 *
 * 座標は「盤」の中の 0〜1。盤は画面の中央に取る正方形である。
 * 正方形にしているのは、縦長の画面でも等距離が等距離のままであるため。
 * この遊びは幾何のパズルなので、盤が歪むとルールごと壊れる。
 *
 *   lights : [x, y, need]  need を省くと 2(ふたつの波で灯る)。3 なら三重の灯
 *   rocks  : [x, y, r]     波を遮る岩。岩の裏には波が回り込まない
 *   drops  : 使える波の数。余分は持たせない
 *
 * 面の作りかた(効く形は二つだけ):
 *   1. 二つの波を同時に置くと、その二点の垂直二等分線の上にある灯が灯る
 *   2. 灯った灯は自分の波を出す。だから灯どうしの二等分線にも次が灯る(連鎖)
 * ========================================================================= */
(function (global) {
  'use strict';

  global.STAGES = [
    // 一 — 灯を挟む。これだけ分かればいい
    { lights: [[0.50, 0.50]], rocks: [], drops: 2 },

    // 二 — 灯が二つ。挟むのではなく、二つが並ぶ線を上下から挟む
    { lights: [[0.24, 0.44], [0.76, 0.44]], rocks: [], drops: 2 },

    // 三 — 下の二つが灯れば、その二つが出した波が上で重なる(連鎖)
    { lights: [[0.50, 0.18], [0.26, 0.60], [0.74, 0.60]], rocks: [], drops: 2 },

    // 四 — 岩。下から届かないので、灯と同じ高さに並べる
    { lights: [[0.50, 0.18]], rocks: [[0.50, 0.44, 0.11]], drops: 2 },

    // 五 — 三重の灯。二つでは足りない
    { lights: [[0.50, 0.50, 3]], rocks: [], drops: 3 },

    // 六 — 岩を挟んで離れた二つ。一対では両方に届かない
    { lights: [[0.26, 0.28], [0.74, 0.72]], rocks: [[0.50, 0.50, 0.12]], drops: 4 },

    // 七 — 岩が上を塞ぐ。下の二つを灯し、その連鎖を岩の脇から通す
    { lights: [[0.50, 0.14], [0.28, 0.62], [0.72, 0.62]], rocks: [[0.50, 0.38, 0.08]], drops: 2 },

    // 八 — 三重の灯の上に岩。三角をひっくり返す
    { lights: [[0.50, 0.50, 3]], rocks: [[0.50, 0.30, 0.08]], drops: 3 },

    // 九 — 二対で五つ。横の一対が連鎖して真ん中の上へ抜ける
    { lights: [[0.50, 0.16], [0.20, 0.44], [0.80, 0.44], [0.34, 0.80], [0.66, 0.80]],
      rocks: [[0.50, 0.54, 0.07]], drops: 4 }
  ];
})(window);
